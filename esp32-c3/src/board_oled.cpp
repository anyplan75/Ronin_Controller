void boardOledBegin(bool want) {
  enabled = want;
  ready = false;
  usedSda = -1;
  usedScl = -1;
  if (!enabled) return;
#if defined(BOARD_SLOT_OLED)
  for (size_t i = 0; i < sizeof(kPairs) / sizeof(kPairs[0]); i++) {
    int sda = kPairs[i][0];
    int scl = kPairs[i][1];
    if (!softProbe(sda, scl)) continue;
    usedSda = sda;
    usedScl = scl;
    if (!oledInit()) {
      usedSda = -1;
      usedScl = -1;
      continue;
    }
    clearScreen();
    ready = true;
    boardOledShow("OLED RS2", "starting", "");
    return;
  }
#endif
}

bool boardOledReady() { return ready; }

void boardOledShow(const char* line1, const char* line2, const char* line3) {
  if (!ready) return;
#if defined(BOARD_SLOT_OLED)
  clearScreen();
  drawLine(0, line1);
  drawLine(2, line2);
  drawLine(4, line3);
#else
  (void)line1;
  (void)line2;
  (void)line3;
#endif
}
