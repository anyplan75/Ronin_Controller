static void sdaOut(int sda, bool hi) {
  pinMode(sda, OUTPUT);
  digitalWrite(sda, hi ? HIGH : LOW);
}
static void sclOut(int scl, bool hi) {
  pinMode(scl, OUTPUT);
  digitalWrite(scl, hi ? HIGH : LOW);
}
static void sdaIn(int sda) { pinMode(sda, INPUT_PULLUP); }
static void sclIn(int scl) { pinMode(scl, INPUT_PULLUP); }
static void delayHalf() { delayMicroseconds(5); }

static bool waitHigh(int pin, uint32_t usCap) {
  uint32_t start = micros();
  while (digitalRead(pin) == LOW) {
    if ((micros() - start) > usCap) return false;
  }
  return true;
}

static bool softStart(int sda, int scl) {
  sdaIn(sda);
  sclIn(scl);
  if (!waitHigh(sda, 200) || !waitHigh(scl, 200)) return false;
  delayHalf();
  sdaOut(sda, false);
  delayHalf();
  sclOut(scl, false);
  delayHalf();
  return true;
}

static void softStop(int sda, int scl) {
  sdaOut(sda, false);
  delayHalf();
  sclOut(scl, true);
  if (!waitHigh(scl, 200)) return;
  delayHalf();
  sdaOut(sda, true);
  delayHalf();
  sdaIn(sda);
  sclIn(scl);
}

static bool softWriteByte(int sda, int scl, uint8_t value) {
  for (int i = 7; i >= 0; i--) {
    sdaOut(sda, (value >> i) & 1);
    delayHalf();
    sclOut(scl, true);
    if (!waitHigh(scl, 200)) return false;
    delayHalf();
    sclOut(scl, false);
    delayHalf();
  }
  sdaIn(sda);
  delayHalf();
  sclOut(scl, true);
  if (!waitHigh(scl, 200)) return false;
  delayHalf();
  bool ack = (digitalRead(sda) == LOW);
  sclOut(scl, false);
  delayHalf();
  return ack;
}

static bool softProbe(int sda, int scl) {
  if (!softStart(sda, scl)) {
    softStop(sda, scl);
    return false;
  }
  bool ok = softWriteByte(sda, scl, 0x3C << 1);
  softStop(sda, scl);
  return ok;
}

static bool i2cBegin(int sda, int scl) {
  if (!softStart(sda, scl)) return false;
  if (!softWriteByte(sda, scl, 0x3C << 1)) {
    softStop(sda, scl);
    return false;
  }
  return true;
}

static bool i2cWrite(int sda, int scl, uint8_t v) { return softWriteByte(sda, scl, v); }

static void cmd(uint8_t c) {
  if (!i2cBegin(usedSda, usedScl)) return;
  i2cWrite(usedSda, usedScl, 0x00);
  i2cWrite(usedSda, usedScl, c);
  softStop(usedSda, usedScl);
}

static void cmd2(uint8_t c, uint8_t a) {
  if (!i2cBegin(usedSda, usedScl)) return;
  i2cWrite(usedSda, usedScl, 0x00);
  i2cWrite(usedSda, usedScl, c);
  i2cWrite(usedSda, usedScl, a);
  softStop(usedSda, usedScl);
}

static bool oledInit() {
  // SSD1306 72x40 (EastRising) 기본 초기화
  cmd(0xAE);
  cmd2(0xD5, 0x80);
  cmd2(0xA8, 0x27);
  cmd2(0xD3, 0x00);
  cmd(0x40);
  cmd2(0x8D, 0x14);
  cmd(0x20);
  cmd(0x00);
  cmd(0xA1);
  cmd(0xC8);
  cmd2(0xDA, 0x12);
  cmd2(0x81, 0xCF);
  cmd2(0xD9, 0xF1);
  cmd2(0xDB, 0x40);
  cmd(0xA4);
  cmd(0xA6);
  cmd(0xAF);
  return true;
}

static void clearScreen() {
  for (uint8_t page = 0; page < 5; page++) {
    cmd(0xB0 | page);
    cmd(0x0C);  // 72x40 가로 오프셋
    cmd(0x11);
    if (!i2cBegin(usedSda, usedScl)) return;
    i2cWrite(usedSda, usedScl, 0x40);
    for (int x = 0; x < 72; x++) i2cWrite(usedSda, usedScl, 0x00);
    softStop(usedSda, usedScl);
  }
}

static void drawChar(uint8_t page, uint8_t col, char ch) {
  if (ch < 0x20 || ch > 0x7E) ch = '?';
  const uint8_t* g = kFont5x7[(uint8_t)ch - 0x20];
  cmd(0xB0 | page);
  uint8_t raw = (uint8_t)(col + 12);  // 72x40 오프셋
  cmd(0x00 | (raw & 0x0F));
  cmd(0x10 | (raw >> 4));
  if (!i2cBegin(usedSda, usedScl)) return;
  i2cWrite(usedSda, usedScl, 0x40);
  for (int i = 0; i < 5; i++) i2cWrite(usedSda, usedScl, g[i]);
  i2cWrite(usedSda, usedScl, 0x00);
  softStop(usedSda, usedScl);
}

static void drawLine(uint8_t page, const char* text) {
  if (text == nullptr) text = "";
  uint8_t col = 0;
  for (size_t i = 0; text[i] && col + 6 <= 72; i++) {
    drawChar(page, col, text[i]);
    col = (uint8_t)(col + 6);
  }
}

